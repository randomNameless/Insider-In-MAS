#!/usr/bin/env python
"""No-attacker control for Experiment 1.

Agent 3 is a normal NEUTRAL cooperative agent generated by the same world model,
not an attacker. Agents 0..2 keep the Experiment-1 mixed personalities
(stubborn, suggestible, neutral). To remain directly comparable with every attack
evaluation, consensus is the unchanged AttackEnv endpoint over agents 0..2.
"""
from __future__ import annotations

import os
os.environ.setdefault("VLLM_WORKER_MULTIPROC_METHOD", "spawn")
os.environ.setdefault("VLLM_BATCH_INVARIANT", "0")

import argparse
import json
import random
from pathlib import Path

import numpy as np
import torch

from RL_attack_env_qwen import (
    AttackEnv,
    QwenWorldModelHF,
    QwenWorldModelVLLM,
    parse_pos_msg,
)

from attacker.prompts import build_chat
from eval_attacks_consensus import benign_predict_many, _render_wm_prompt


CONTROL_PERSONALITIES = ["stubborn", "suggestible", "neutral", "neutral"]
CONTROL_NAME = "neutral_control"


def neutral_agent3_batch(wm, envs):
    """Generate agent 3's cooperative Message/Position with the victim WM."""
    chats = [
        build_chat(
            3,
            "neutral",
            [int(x) for x in env.pos],
            list(env.last_messages),
            int(env.t),
            msg_order="index",
        )
        for env in envs
    ]
    raws = wm._generate([_render_wm_prompt(wm, chat) for chat in chats])
    return [
        parse_pos_msg(raw, int(env.pos[3]), wm.max_pos)
        for env, raw in zip(envs, raws)
    ]


def run_batch(envs, wm, init_positions, record_flags):
    states = []
    for env, init_pos, record in zip(envs, init_positions, record_flags):
        env.reset(options={
            "positions": list(init_pos),
            "personalities": list(CONTROL_PERSONALITIES),
        })
        states.append({
            "env": env,
            "done": False,
            "consensus": False,
            "ep_len": 0,
            "rounds": [] if record else None,
        })

    while any(not state["done"] for state in states):
        active = [state for state in states if not state["done"]]
        active_envs = [state["env"] for state in active]
        neutral_outputs = neutral_agent3_batch(wm, active_envs)

        query_groups = []
        pending = []
        for state, (agent3_pos, agent3_msg) in zip(active, neutral_outputs):
            env = state["env"]
            t = int(env.t)
            before = [int(x) for x in env.pos]
            # All four agents read the untouched round-start snapshot.  Do not
            # stage agent 3's proposal until every response has been generated.
            queries = [(env._build_messages(i), int(env.pos[i])) for i in range(3)]
            query_groups.append(queries[:3])
            pending.append((t, before, int(agent3_pos), agent3_msg))

        pred_groups = benign_predict_many(wm, query_groups)
        for state, preds, saved in zip(active, pred_groups, pending):
            env = state["env"]
            t, before, agent3_pos, agent3_msg = saved
            env.prepare(agent3_pos)
            env._pending_atk_msg = agent3_msg
            _, _, terminated, truncated, _ = env.apply(preds)
            state["ep_len"] += 1
            state["consensus"] = bool(terminated)
            state["done"] = bool(terminated or truncated)
            if state["rounds"] is not None:
                state["rounds"].append({
                    "t": t,
                    "positions_before": before,
                    "neutral_agent3_pos": agent3_pos,
                    "neutral_agent3_msg": agent3_msg,
                    "positions_after": [int(x) for x in env.pos],
                    "agents_0_to_2_outputs": [
                        {"position": int(pos), "message": msg}
                        for pos, msg in preds
                    ],
                    "consensus_after": bool(terminated),
                })

    return states


def main():
    p = argparse.ArgumentParser(
        description="Experiment-1 no-attacker control: agent 3 is neutral")
    p.add_argument("--wm_model_dir", default="~/models/qwen35-wm-vllm")
    p.add_argument("--wm_backend", default="vllm", choices=["vllm", "hf"])
    p.add_argument("--n_exp", type=int, default=200)
    p.add_argument("--max_pos", type=int, default=20)
    p.add_argument("--max_steps", type=int, default=10)
    p.add_argument("--consensus_tol", type=float, default=0.0)
    p.add_argument("--consensus_penalty", type=float, default=-10.0)
    p.add_argument("--seed", type=int, default=9000)
    p.add_argument("--wm_temperature", type=float, default=0.7)
    p.add_argument("--wm_max_new_tokens", type=int, default=200)
    p.add_argument("--eval_batch_size", type=int, default=8)
    p.add_argument("--wm_gpu_mem_util", type=float, default=0.65)
    p.add_argument("--max_model_len", type=int, default=2048)
    p.add_argument("--enforce_eager", action="store_true")
    p.add_argument("--log_every", type=int, default=0)
    p.add_argument("--dump_json", default=None)
    p.add_argument("--dump_n", type=int, default=5)
    args = p.parse_args()

    if args.eval_batch_size < 1:
        p.error("--eval_batch_size must be >= 1")

    model_dir = os.path.expanduser(args.wm_model_dir)
    chat_kwargs = {"enable_thinking": False}
    if args.wm_backend == "vllm":
        wm = QwenWorldModelVLLM(
            model_dir=model_dir,
            max_pos=args.max_pos,
            max_new_tokens=args.wm_max_new_tokens,
            gpu_memory_utilization=args.wm_gpu_mem_util,
            max_model_len=args.max_model_len,
            enforce_eager=args.enforce_eager,
            chat_template_kwargs=chat_kwargs,
            temperature=args.wm_temperature,
            seed=args.seed,
        )
    else:
        wm = QwenWorldModelHF(
            model_dir=model_dir,
            max_pos=args.max_pos,
            max_new_tokens=args.wm_max_new_tokens,
            chat_template_kwargs=chat_kwargs,
        )

    def make_env():
        return AttackEnv(
            world_model=wm,
            max_pos=args.max_pos,
            max_steps=args.max_steps,
            consensus_tol=args.consensus_tol,
            consensus_penalty=args.consensus_penalty,
            reward_mode="spread",
            attacker_msg_mode="template",
        )

    initial_positions = []
    for exp_idx in range(args.n_exp):
        er = random.Random(args.seed + exp_idx + args.max_steps * 1000)
        initial_positions.append([
            er.randint(0, args.max_pos) for _ in range(4)
        ])

    policy_seed = args.seed + 100_000
    random.seed(policy_seed)
    np.random.seed(policy_seed % (2 ** 32))
    torch.manual_seed(policy_seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(policy_seed)
    if hasattr(wm, "sampling"):
        wm.sampling.seed = args.seed + 200_000

    consensus_count = 0
    ep_len_sum = 0
    records = []
    for start in range(0, args.n_exp, args.eval_batch_size):
        stop = min(start + args.eval_batch_size, args.n_exp)
        indices = list(range(start, stop))
        states = run_batch(
            [make_env() for _ in indices],
            wm,
            [initial_positions[i] for i in indices],
            [args.dump_json is not None and i < args.dump_n for i in indices],
        )
        for exp_idx, state in zip(indices, states):
            consensus_count += int(state["consensus"])
            ep_len_sum += int(state["ep_len"])
            if state["rounds"] is not None:
                records.append({
                    "condition": CONTROL_NAME,
                    "exp_idx": exp_idx,
                    "init_positions": initial_positions[exp_idx],
                    "personalities": list(CONTROL_PERSONALITIES),
                    "consensus": state["consensus"],
                    "ep_len": state["ep_len"],
                    "rounds": state["rounds"],
                })
            if args.log_every > 0 and (
                    exp_idx % args.log_every == 0 or exp_idx == args.n_exp - 1):
                status = "CONSENSUS" if state["consensus"] else "NO CONSENSUS"
                print(f"[{CONTROL_NAME}] exp {exp_idx:4d} {status} "
                      f"ep_len={state['ep_len']}", flush=True)

    rate = consensus_count / max(1, args.n_exp)
    mean_len = ep_len_sum / max(1, args.n_exp)
    summary = {
        "episodes": args.n_exp,
        "consensus": consensus_count,
        "rate": rate,
        "mean_ep_len": mean_len,
    }
    print("\n" + "#" * 74)
    print("# NO-ATTACKER CONTROL: agent 3 is a normal neutral WM agent")
    print("# personalities = ['stubborn', 'suggestible', 'neutral', 'neutral']")
    print("# consensus scope = agents 0..2 (identical to attacker evaluation)")
    print("#" * 74)
    print(f"condition={CONTROL_NAME:15s} episodes={args.n_exp:4d} "
          f"consensus={consensus_count:4d} rate={rate:.3f} "
          f"mean_ep_len={mean_len:.2f}", flush=True)

    if args.dump_json:
        out = Path(args.dump_json).expanduser()
        out.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "condition": CONTROL_NAME,
            "consensus_scope": "agents_0_to_2",
            "personalities": list(CONTROL_PERSONALITIES),
            "n_exp": args.n_exp,
            "seed": args.seed,
            "summary": summary,
            "episodes": records,
        }
        out.write_text(json.dumps(payload, ensure_ascii=False, indent=2),
                       encoding="utf-8")
        print(f"[dump] wrote {len(records)} episodes -> {out}", flush=True)


if __name__ == "__main__":
    main()
